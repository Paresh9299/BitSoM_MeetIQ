  function appendMessage(text, type) {
    const chat = $("chatMessages");
    const msg = document.createElement("div");
    msg.className = `msg ${type}`;
    msg.textContent = text;
    chat.appendChild(msg);
    chat.scrollTop = chat.scrollHeight;
  }
  
  function sendSuggestedPrompt(text) {
    $("chatInput").value = text;
    sendChat();
  }
  
  function getAssistantResponse(input, company) {
    const q = input.toLowerCase();
  
    if (q.includes("30 seconds") || q.includes("summarize")) {
      return `${currentCompanyName()} in 30 seconds: ${company.summaryBullets.slice(0, 3).join(" ")} Focus the discussion on ${company.talkingPoints[0].toLowerCase()} and ${company.talkingPoints[1].toLowerCase()}.`;
    }
  
    if (q.includes("risk")) {
      return `Top risk view: ${company.riskAlerts.map(r => r.text).join(" Also, ")}`;
    }
  
    if (q.includes("last meeting")) {
      return `Since the last meeting: ${company.lastMeetingSummary}`;
    }
  
    if (q.includes("opening line")) {
      return company.openingLine.replace("Suggested opening line: ", "");
    }
  
    if (q.includes("financial") || q.includes("revenue") || q.includes("margin")) {
      return `${currentCompanyName()} synthetic financial snapshot: revenue ${company.revenue}, growth ${company.growth}, EBITDA margin ${company.margin}.`;
    }
  
    return `${company.assistantRecommendation} You can also ask about risks, last meeting context, or a 30-second summary.`;
  }
  
  function sendChat() {
    const input = $("chatInput");
    const text = input.value.trim();
    if (!text) return;
  
    const company = companyData[currentCompanyName()];
    appendMessage(text, "user");
    const reply = getAssistantResponse(text, company);
  
    setTimeout(() => {
      appendMessage(reply, "bot");
    }, 250);
  
    input.value = "";
  }
  
